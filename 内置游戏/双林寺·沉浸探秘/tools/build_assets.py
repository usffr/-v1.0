"""双林寺 · 沉浸探秘 —— 素材整理

按《双林寺照片分类清单.md》的编号，从上级项目的 new/ 中挑选实际存在的照片，
归类为各殿宇素材，并迁入音频 / 视频。

输出：
  assets/photos/<hall>/*.png     各殿宇照片（保留原始编号）
  assets/photos/_relics/*.png    器物彩蛋
  assets/audio/古寺星沉.mp3
  assets/video/总览视频.mp4
  data/photos.js                 照片清单（殿宇 -> 文件列表）
"""
import os
import json
import shutil

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UP = os.path.dirname(BASE)                    # 上级：小游戏《双林古寺·像素探秘》
SRC = os.path.join(UP, "new")                 # 实际素材来源
PHOTOS = os.path.join(BASE, "assets", "photos")

# 殿宇 -> 清单编号（清单 .JPG 对应 new/ 中的 .png）
GROUPS = {
    "shanmen":     ["DSC_9936"],                                   # 山门 / 文保碑
    "tianwang":    ["DSC_9941", "DSC_1511"],                       # 天王殿
    "qianfo":      ["DSC_1518", "DSC_1519", "DSC_1507", "DSC_1503", "DSC_1525"],  # 千佛殿·韦陀
    "qianfo_wall": ["DSC_9918", "DSC_1584", "DSC_1565"],           # 千佛殿·壁塑
    "pusa":        ["DSC_1425"],                                   # 菩萨殿·千手观音
    "luohan":      ["DSC_9927", "DSC_9933", "DSC_9943"],           # 罗汉殿·悬塑
    "luohan_rem":  ["DSC_9956", "DSC_9925", "DSC_9923", "DSC_9955"],  # 罗汉殿·残件
    "caisu":       ["DSC_1388", "DSC_1400", "DSC_1431", "DSC_1454"],  # 悬塑群像 / 坐佛
    "xingtai":     ["DSC_1397"],                                   # 戏台/藻井装饰
    "relics":      ["DSC_2813", "DSC_2819", "DSC_2863"],           # 器物（彩蛋）
}


def find_src(stem):
    for ext in (".png", ".jpg", ".JPG", ".jpeg"):
        p = os.path.join(SRC, stem + ext)
        if os.path.exists(p):
            return p
    return None


def main():
    if os.path.exists(PHOTOS):
        shutil.rmtree(PHOTOS)
    os.makedirs(PHOTOS, exist_ok=True)
    manifest = {}
    for hall, stems in GROUPS.items():
        rel = "_relics" if hall == "relics" else hall
        outdir = os.path.join(PHOTOS, rel)
        os.makedirs(outdir, exist_ok=True)
        files = []
        for s in stems:
            src = find_src(s)
            if not src:
                print("  [missing]", s)
                continue
            dst = os.path.join(outdir, s + ".png")
            shutil.copy(src, dst)
            files.append(f"assets/photos/{rel}/{s}.png")
        manifest[hall] = files
        print(f"{hall}: {len(files)} 张")

    # 音频 / 视频
    os.makedirs(os.path.join(BASE, "assets", "audio"), exist_ok=True)
    os.makedirs(os.path.join(BASE, "assets", "video"), exist_ok=True)
    shutil.copy(os.path.join(UP, "古寺星沉.mp3"), os.path.join(BASE, "assets", "audio", "古寺星沉.mp3"))
    shutil.copy(os.path.join(SRC, "总览视频.mp4"), os.path.join(BASE, "assets", "video", "总览视频.mp4"))

    with open(os.path.join(BASE, "data", "photos.js"), "w", encoding="utf-8") as f:
        f.write("// auto-generated by tools/build_assets.py\nconst PHOTOS = ")
        f.write(json.dumps(manifest, ensure_ascii=False, indent=1))
        f.write(";\n")
    print("done")


if __name__ == "__main__":
    main()
